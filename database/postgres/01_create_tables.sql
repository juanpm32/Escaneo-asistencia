  PostgreSQL 13 o superior (Render).
  Ejecutar sobre la base que Render ya creo. No crea la base.
  Se puede ejecutar mas de una vez.
*/

CREATE TABLE IF NOT EXISTS tbl_personas (
    id_persona       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_dni       VARCHAR(8)  NOT NULL,
    nombres          VARCHAR(150) NULL,
    apellido_paterno VARCHAR(100) NULL,
    apellido_materno VARCHAR(100) NULL,
    estado           BOOLEAN     NOT NULL DEFAULT TRUE,
    fecha_creacion   TIMESTAMP   NOT NULL,
    CONSTRAINT uq_tbl_personas_numero_dni UNIQUE (numero_dni)
);

CREATE TABLE IF NOT EXISTS tbl_asistencias (
    id_asistencia       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona          INT         NOT NULL,
    numero_dni          VARCHAR(8)  NOT NULL,
    fecha_asistencia    DATE        NOT NULL,
    hora_asistencia     TIME(0)     NOT NULL,
    fecha_hora_registro TIMESTAMP   NOT NULL,
    tipo_asistencia     VARCHAR(10) NOT NULL,
    estado              VARCHAR(15) NOT NULL,
    dispositivo         VARCHAR(150) NULL
);

CREATE TABLE IF NOT EXISTS tbl_configuracion (
    id_configuracion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave            VARCHAR(100) NOT NULL,
    valor            VARCHAR(250) NOT NULL,
    descripcion      VARCHAR(250) NULL
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_tbl_asistencias_tbl_personas'
    ) THEN
        ALTER TABLE tbl_asistencias
            ADD CONSTRAINT fk_tbl_asistencias_tbl_personas
            FOREIGN KEY (id_persona) REFERENCES tbl_personas (id_persona);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_tbl_asistencias_numero_dni
    ON tbl_asistencias (numero_dni);

CREATE INDEX IF NOT EXISTS ix_tbl_asistencias_fecha_asistencia
    ON tbl_asistencias (fecha_asistencia);

INSERT INTO tbl_configuracion (clave, valor, descripcion)
SELECT
    'INTERVALO_DUPLICADO_MINUTOS',
    '5',
    'Minutos durante los cuales el mismo DNI no puede volver a registrar asistencia'
WHERE NOT EXISTS (
    SELECT 1 FROM tbl_configuracion WHERE clave = 'INTERVALO_DUPLICADO_MINUTOS'
);

INSERT INTO tbl_configuracion (clave, valor, descripcion)
SELECT
    'TIPO_ASISTENCIA_DEFAULT',
    'ENTRADA',
    'Tipo de asistencia que graba el sistema'
WHERE NOT EXISTS (
